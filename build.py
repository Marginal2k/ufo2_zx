#!/usr/bin/env python3
"""Build UFO-2: assets + sources -> build/ufo2.trd (one plain TR-DOS disk, no protection).

    python build.py
    SJASMPLUS=/path/to/sjasmplus python build.py

Steps (docs/BUILD.md):
 1. tools/mkdata.py: assets/ -> build/data/ (sprites, texts, pictures in the game's formats)
 2. the ending is assembled, the 73 disk resources are packed, their places on the disk are fixed
    (build/disk_layout.inc - included by src/game/disk.asm)
 3. the game is assembled; its four overlays are packed into page 0
 4. title, manual, intro are assembled; all loader files are packed; build/boot_layout.inc; the loader
 5. the disk image
"""
import os
import shutil
import struct
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import zx0
import mkdata
from trd import Trd, basic_program, SPT

B = os.path.join(ROOT, 'build')
DATA = os.path.join(B, 'data')
SJ = os.environ.get('SJASMPLUS') or shutil.which('sjasmplus') or r'c:\sjasmplus\sjasmplus.exe'
LOADER_SECTORS = 4          # room kept for the loader file "ufo2" in front of the resources
SAVE_SECTORS = 16           # the saved game


def rd(*p):
    with open(os.path.join(*p), 'rb') as f:
        return f.read()


def asm(name, extra_inc=()):
    """Assemble src/<name>/main.asm into build/<name>/ (SAVEBIN outputs, main.lst, main.sym)."""
    out = os.path.join(B, name)
    os.makedirs(out, exist_ok=True)
    cmd = [SJ, '--nologo', '--msg=err', '--lst=main.lst', '--sym=main.sym', '-I', os.path.join(ROOT, 'src', name),
           '-I', os.path.join(ROOT, 'src', 'lib'), '-I', DATA, '-I', B]
    for i in extra_inc:
        cmd += ['-I', i]
    r = subprocess.run(cmd + [os.path.join(ROOT, 'src', name, 'main.asm')], capture_output=True, text=True, cwd=out)
    if r.returncode:
        sys.exit(f'assembly of src/{name} failed:\n{r.stdout}{r.stderr}')
    return out


def check_in_place(name, packed, load_addr, dest, size):
    """The block is loaded to load_addr and unpacked to dest over itself: is that safe?"""
    gap = (load_addr + len(packed)) - (dest + size)
    if zx0.inplace_margin(packed, gap) < 0:
        sys.exit(f'{name}: cannot be unpacked in place (packed data would be overwritten)')


def main():
    os.makedirs(B, exist_ok=True)
    mkdata.main()

    # ---- 2. resources
    asm('ending')
    res = []
    for i, n in enumerate(mkdata.RES):
        raw = rd(B, 'ending', 'xend.bin') if n == 'end' else rd(DATA, 'res_raw', f'{i + 1:02}_{n}.bin')
        p = mkdata.pack(raw)
        if n.startswith('up'):          # encyclopedia: moved to the top of the page (#FFFE), unpacked to #C000 (USA, xlix.asm)
            check_in_place(n, p, 0xFFFF - len(p), 0xC000, len(raw))
        elif n == 'end':                # the ending: loaded to #C000+9800, unpacked to #C000 (POBEDA, xlif.asm)
            check_in_place(n, p, 0xC000 + 9800, 0xC000, len(raw))
        elif len(p) > 0xB800 - 0x9000:  # the others are loaded to DSCR (#9000) and unpacked to #B800 or #E000
            sys.exit(f'resource {n}: packed size {len(p)} does not fit between #9000 and #B800')
        res.append((n, p))
    disk = Trd('UFO2')
    basic = basic_program([(10, 'CLEAR VAL "24575": RANDOMIZE USR VAL "15619": REM : LOAD "ufo2" CODE'),
                           (20, 'RANDOMIZE USR VAL "24576"')])
    disk.add_file('boot', 'B', basic, start=len(basic), length=len(basic))
    loader_at = disk.alloc(LOADER_SECTORS)          # the catalogue entry is added when the loader is assembled
    loader_entry = len(disk.files)
    disk.files.append(None)
    lay = ['; generated by build.py: where the resources and the saved game are on the disk',
           '; (logical track = cylinder*2 + side, sector 1..16, number of sectors)']
    tab = []
    for i, (n, p) in enumerate(res):
        s = disk.add_file(n, 'C', p, start=0xC000)
        tab.append(f'\tDEFB\t{s // SPT},{s % SPT + 1},{(len(p) + 255) // 256}\t; {i + 1} {n}')
    s = disk.add_file('ufo2save', 'C', bytes(SAVE_SECTORS * 256), start=0x4000)
    lay.append(f'SAVEPOS\tEQU\t{s // SPT}*256+{s % SPT + 1}')
    lay.append('RESTAB')
    with open(os.path.join(B, 'disk_layout.inc'), 'w', newline='\n') as f:
        f.write('\n'.join(lay + tab) + '\n')

    # ---- 3. the game
    g = asm('game')
    main_bin = bytearray(rd(g, 'main.bin'))
    sym = {}
    for ln in open(os.path.join(g, 'main.sym')):
        a = ln.split(': EQU ')
        if len(a) == 2:
            sym[a[0]] = int(a[1], 16)
    page0 = b''
    for k, n in enumerate(('lesha', 'xlix', 'xlic', 'xlif')):
        p = mkdata.pack(rd(g, f'ovl_{n}.bin'))
        struct.pack_into('<H', main_bin, sym['OVLTAB'] - 0x4000 + k * 2, 0xC000 + len(page0) + 2)     # the stream after its length word
        page0 += p
    if len(page0) > 16384:
        sys.exit(f'the packed overlays do not fit into page 0: {len(page0)} bytes')
    print(f'game: resident {len(main_bin)} bytes (#4000-#{0x4000 + len(main_bin) - 1:04X}), overlays packed {len(page0)} of 16384')
    if len(main_bin) > 0x9200 - 0x4000:
        sys.exit('the game does not fit below the place its packed copy is loaded to (MAINLD in src/boot/boot.asm)')

    # ---- 4. the other programs and the loader files
    t, m, it = asm('title'), asm('manual'), asm('intro')
    BUF = 0x7000                      # as in src/boot/main.asm
    files = [  # name on the disk, label in the loader, unpacked data, where it runs (None: loaded as it is to #C000)
        ('title', 'F_TITLE', rd(t, 'title.bin'), 0x7000),
        ('manual7', 'F_MANUAL7', rd(m, 'manual7.bin'), 0xDB00),
        ('manual', 'F_MANUAL', rd(m, 'manual.bin'), 0x7000),
        ('page7', 'F_PAGE7', rd(g, 'page7.bin'), 0xC000),
        ('page0', 'F_PAGE0', page0, None),
        ('page1', 'F_PAGE1', rd(g, 'page1.bin'), 0xC000),
        ('page3', 'F_PAGE3', rd(g, 'page3.bin'), 0xC000),
        ('page4', 'F_PAGE4', rd(g, 'page4.bin'), 0xC000),
        ('game', 'F_MAIN', bytes(main_bin), 0x4000),
        ('demo0', 'F_DEMO0', rd(DATA, 'xdemo0.dat'), 0xC000),
        ('demo1', 'F_DEMO1', rd(DATA, 'xdemo1.dat'), 0xC000),
        ('demo2', 'F_DEMO2', rd(DATA, 'xdemo2.dat'), 0xC000),
        ('demos6', 'F_DEMOS6', rd(DATA, 'xdemos6.dat'), 0xC000),
        ('demos7', 'F_DEMOS7', rd(DATA, 'xdemos7.dat'), 0xC000),
        ('demotxt', 'F_DEMOTXT', rd(DATA, 'xdemotxt.dat'), 0xC000),
        ('intro', 'F_INTRO', rd(it, 'intro.bin'), 0x7000),
    ]
    lay = ['; generated by build.py: the files the loader reads',
           '; (track, sector 0..15, number of sectors, high byte of the address the file is loaded to)']
    lay.append(f'DSKDRV\tEQU\t#{sym["DSKDRV"]:04X}\t; in the game: the drive it was loaded from')
    tab = ['FTAB']
    for k, (n, lab, data, dest) in enumerate(files):
        packed = data if dest is None else mkdata.pack(data)
        cnt = (len(packed) + 255) // 256
        if dest is None:
            load = 0xC000
        elif n == 'game':
            load = 0x9200
            if load + cnt * 256 > 0xFF00 - 64:
                sys.exit('the packed game is too long for the loader')
        elif dest >= 0xC000:
            load = BUF                      # unpacked from the buffer
            if BUF + cnt * 256 > 0xC000:
                sys.exit(f'{n}: packed file does not fit into the loader buffer')
        else:                               # a program for #7000: loaded as high as possible, unpacked over itself
            top = 0xC000 if n == 'intro' else 0x10000
            load = top - cnt * 256
            check_in_place(n, packed, load, dest, len(data))
        s = disk.add_file(n, 'C', packed, start=load)
        lay.append(f'{lab}\tEQU\t{k}')
        tab.append(f'\tDEFB\t{s // SPT},{s % SPT},{cnt},#{load >> 8:02X}\t; {n}')
    with open(os.path.join(B, 'boot_layout.inc'), 'w', newline='\n') as f:
        f.write('\n'.join(lay + tab) + '\n')
    bt = asm('boot')
    loader = rd(bt, 'boot.bin')
    if len(loader) > LOADER_SECTORS * 256:
        sys.exit('the loader is longer than the room kept for it (LOADER_SECTORS)')
    disk.img[loader_at * 256:loader_at * 256 + len(loader)] = loader
    nm = b'ufo2    C' + struct.pack('<HH', 0x6000, len(loader)) + bytes([LOADER_SECTORS, loader_at % SPT, loader_at // SPT])
    disk.files[loader_entry] = nm

    # ---- 5. the disk
    path = os.path.join(B, 'ufo2.trd')
    disk.save(path)
    used = disk.next * 256
    print(f'build/ufo2.trd: {len(disk.files)} files, {used} bytes used ({used * 100 // (160 * SPT * 256)}% of the disk)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
