; UFO-2: the disk layer (replaces XIOD.A80 of 1996, see src/original/xiod.asm).
;
; Everything the game does with the disk goes through this file:
;   READ     A = number of a resource (1..73, see tools/mkdata.py), HL = address: load the packed resource
;   D_READ   D = logical track, E = sector (1..16), B = number of sectors, HL = address; CY = error
;   D_WRITE  the same registers, writes
;   TR000    recalibrate the drive (before a retry)
; The saved game uses D_READ/D_WRITE with the position SAVEPOS (SET_LS in xlic.asm).
;
; The disk is a plain TR-DOS one: 256-byte sectors 1..16, logical track = cylinder*2 + side. Where each resource
; lies is listed in build/disk_layout.inc, generated by tools/mktrd.py - the files can be seen in the catalogue,
; but the game reads them by position.
;
; The game keeps its code in the screen area and over the system variables (#4000..), so the TR-DOS entry
; #3D13 cannot be used here. As in 1996 the sectors are read with pieces of the TR-DOS 5.03 ROM, entered through
; #3D2F: #2A53 (OUT (C),A), #3EF5 (wait for the controller), #2090 (read a sector), #2FC3/#3FCA (write a sector),
; #2F5F/#2F65 (restore). The ROM stores its error code at #5CD6 - a byte of the game code, saved and put back here.
; To port the game to another disk system only this file has to be rewritten.

	INCLUDE "disk_layout.inc"	; SAVEPOS, RESTAB

; position the head: D = logical track
POS	LD	A,(DSKDRV)
	AND	3
	OR	#3C	; side 0, MFM, no reset
	BIT	0,D
	JR	Z,DW_SID
	RES	4,A	; side 1
DW_SID	LD	C,#FF
	CALL	RG_DOS
	LD	A,D
	SRL	A
	LD	C,#7F
	CALL	RG_DOS
	LD	A,#18	; seek
	LD	C,#1F
	CALL	RG_DOS
	CALL	COM_EX
	DI
	RET

RD_SCT	LD	BC,RD_SCT
	PUSH	BC
	LD	BC,#17F
	LD	IX,#2090
	JR	DOS

RG_DOS	LD	IX,#2A53
	JR	DOS

COM_EX	LD	IX,#3EF5
DOS	PUSH	IX
	JP	#3D2F

ERR_RW	SCF
	RET

TR000	CALL	TR0
TR0	CALL	TR00
TR00	DI
	LD	IX,#2F5F
	CALL	DOS
	LD	IX,#2F65
	JP	DOS

; next sector: E = 1..16, then the next logical track
NXTSEC	INC	E
	LD	A,E
	CP	17
	RET	C
	LD	E,1
	INC	D
	JP	POS

READ ;A-No., HL - adr
	PUSH	HL
	LD	L,A
	LD	H,0
	LD	D,H
	LD	E,L
	ADD	HL,HL
	ADD	HL,DE
	LD	DE,RESTAB-3
	ADD	HL,DE
	LD	D,(HL)
	INC	HL
	LD	E,(HL)
	INC	HL
	LD	B,(HL)
	POP	HL
READ1	PUSH	HL
	PUSH	DE
	PUSH	BC
	CALL	D_READ
	POP	BC
	POP	DE
	POP	HL
	RET	NC
	CALL	TR000
	JR	READ1

D_WRITE	DI
	CALL	POS
LOPWR1	PUSH	HL
	PUSH	BC
	LD	C,#5F
	LD	A,E
	CALL	RG_DOS
	CALL	WR_SC
	DI
	POP	BC
	POP	HL
	CALL	NXTSEC
	INC	H
	DJNZ	LOPWR1
	RET

WR_SC	LD	A,#A0
	LD	IX,#2FC3
	CALL	DOS
	LD	IX,#3FCA
	LD	C,#7F
	JP	DOS

D_READ	DI ;E-sec,D-trk,B-sec.num,HL-mem.adr
	CALL	POS
	LD	A,(#5CD6)
	EX	AF,AF'
NXT_S	LD	IXL,3 ;retry.num
NXT_SC	PUSH	HL
	PUSH	BC
	PUSH	IX
	LD	C,#5F
	LD	A,E
	CALL	RG_DOS
	CALL	RD_SCT
	DI
	LD	HL,#5CD6
	EX	AF,AF'
	CP	(HL)
	POP	IX
	JR	Z,GOOD
	LD	(HL),A
	DEC	IXL
	POP	BC
	POP	HL
	JP	Z,ERR_RW
	EX	AF,AF'
	JR	NXT_SC
GOOD	POP	BC
	POP	HL
	EX	AF,AF'
	CALL	NXTSEC
	INC	H
	DJNZ	NXT_S
	XOR	A
	RET
